"""The P2 deferred-reads report: which reads are verified and why the rest are not.

``python -m tools.verify.deferred_report`` writes
docs/superpowers/recon/2026-10-25-api-surface/p2-deferred.md; ``--check`` exits 1 when
the committed file is stale. Reasons come verbatim from the ``DEFERRED`` tables in the
recipe modules; the private-tree areas share one reason (they are P7's job).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from familysearch.api.registry import effective_status
from tools.spec.coverage import load_inputs

from .recipes import RECIPES, reads_misc, reads_standards, reads_tree_persons, reads_tree_relations

REPORT_PATH = (Path(__file__).resolve().parents[2] / "docs" / "superpowers" / "recon"
               / "2026-10-25-api-surface" / "p2-deferred.md")

PRIVATE_TREE_REASON = ("needs a private tree/genealogy/group fixture; creating one is an "
                       "unverified write (P7)")
PRIVATE_TREE_AREAS = ("Genealogies Endpoints", "User Tree Endpoints")

DEFERRED: dict[str, str] = {}
for _module in (reads_tree_persons, reads_tree_relations, reads_standards, reads_misc):
    DEFERRED.update(_module.DEFERRED)

# The later tier whose writes or fixtures unblock each deferred read (P3..P9 per the
# full-API-coverage foundation plan). Private-tree areas are all P7.
TIERS: dict[str, str] = {
    "allowPersonMerge": "P6", "readPersonMerge": "P6",
    "readTreePersonMatches": "P6", "readTreePersonMatchesHeaders": "P6",
    "readPersonNotAMatches": "P6", "performPersonMatchesByExample": "P6",
    "readPersonPortrait": "P5", "readPersonPortraits": "P5",
    "readMemoryComments": "P5", "readUserMemories": "P5",
    "getPreferredParentRelationship": "P3", "readPreferredSpouseRelationship": "P3",
    "readCoupleRelationshipSources": "P4", "readCoupleRelationshipSourceReferences": "P4",
    "getChildAndParentsRelationshipSources": "P4",
    "getChildAndParentsRelationshipSourceReferences": "P4",
    "getSourceDescriptionChanges": "P4", "readSourceFolders": "P4",
    "readUserSourceFolders": "P4", "readUserSourceDescriptions": "P4",
    "readUserDefinedCollection": "P4", "readUserDefinedCollectionSourceDescriptions": "P4",
    "readDiscussion": "P8", "readDiscussionHeaders": "P8", "readComments": "P8",
    "readCurrentUser": "P8", "readCurrentTreePerson": "P8", "readAgent": "P8",
    "readUserHistory": "P8", "readPartnerEligibility": "P8",
    "readPendingModifications": "P8",
    "readPlaceTypes": "P9", "readPlaceTypeGroups": "P9", "checkPlaceIsChild": "P9",
    "getNameScript": "P9",
}


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def build_report() -> str:
    ops, _excluded, _areas, registry = load_inputs()
    reads = sorted((o for o in ops if o.kind == "read"), key=lambda o: o.operation_id)
    recipe_of: dict[str, str] = {}
    for name in sorted(RECIPES):
        for op in RECIPES[name].ops:
            recipe_of.setdefault(op, name)
    verified, deferred = [], []
    for o in reads:
        if effective_status(o.operation_id, o.fingerprint, registry) == "verified":
            verified.append(o)
        else:
            deferred.append(o)
    rows = []
    for o in sorted(deferred, key=lambda o: (o.area, o.operation_id)):
        if o.area in PRIVATE_TREE_AREAS:
            reason, tier = PRIVATE_TREE_REASON, "P7"
        elif o.operation_id in DEFERRED:
            reason, tier = DEFERRED[o.operation_id], TIERS[o.operation_id]
        else:
            raise SystemExit(f"error: {o.operation_id} is an unverified read with no "
                             "recorded deferral reason")
        rows.append(f"| {o.operation_id} | {o.area} | {_cell(reason)} | {tier} |")
    by_recipe: dict[str, list[str]] = {}
    for o in verified:
        by_recipe.setdefault(recipe_of.get(o.operation_id, "(no recipe)"), []).append(
            o.operation_id)
    lines = [
        "# P2 read verification: deferred reads",
        "",
        "Generated by `python -m tools.verify.deferred_report` (`--check` fails when this "
        "file is stale); do not edit by hand. Verified means proven on beta only.",
        "",
        f"Reads: {len(reads)}. Verified: {len(verified)}. Deferred: {len(deferred)}.",
        "",
        "## Deferred reads",
        "",
        "| Operation | Area | Reason unverified | Unblocked by |",
        "|---|---|---|---|",
        *rows,
        "",
        "## Verified reads by recipe",
        "",
        "| Recipe | Reads |",
        "|---|---|",
        *(f"| {name} | {', '.join(sorted(ids))} |" for name, ids in sorted(by_recipe.items())),
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m tools.verify.deferred_report")
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if the committed report is stale")
    parser.add_argument("--path", type=Path, default=REPORT_PATH)
    args = parser.parse_args(argv)
    text = build_report()
    if args.check:
        current = args.path.read_text() if args.path.exists() else None
        if current != text:
            print(f"stale: {args.path} (run python -m tools.verify.deferred_report)",
                  file=sys.stderr)
            return 1
        return 0
    args.path.parent.mkdir(parents=True, exist_ok=True)
    args.path.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
